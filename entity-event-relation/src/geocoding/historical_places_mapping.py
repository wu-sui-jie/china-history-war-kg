def get_modern_name(historical_name: str) -> str:
    """
    获取历史地名对应的现代地名

    Args:
        historical_name: 历史地名

    Returns:
        现代地名，如果未找到则返回原始地名
    """
    return HISTORICAL_MAPPING.get(historical_name, historical_name)


def search_by_keyword(keyword: str) -> dict:
    """
    根据关键词搜索历史地名

    Args:
        keyword: 搜索关键词

    Returns:
        匹配的历史地名字典
    """
    results = {}
    for key, value in HISTORICAL_MAPPING.items():
        if keyword in key or keyword in value:
            results[key] = value
    return results
